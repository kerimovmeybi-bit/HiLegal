// Получаем id из URL
const params = new URLSearchParams(window.location.search);
const id = params.get('id') || 1;

// Функция для обновления контента
function updateTeamContent() {
  const member = i18next.t(`team.cards.${id}`, { returnObjects: true });
  if (!member) return console.error('Team member not found');

  document.querySelector('[data-name]').textContent = member.name;
  document.querySelector('[data-position]').textContent = member.position;
  document.querySelector('[data-img]').src = member.img;
  document.querySelector('[data-email]').textContent = member.email || '';
  document.querySelector('[data-email]').href = member.email ? `mailto:${member.email}` : '#';
  document.querySelector('[data-text1]').innerHTML = member.text1;
  document.querySelector('[data-text2]').innerHTML = member.text2;
  document.querySelector('[data-text3]').innerHTML = member.text3;
  document.querySelector('[data-text4]').innerHTML = member.text4;

  // Перевод статических текстов через data-i18n
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    el.textContent = i18next.t(key);
  });
}

// Инициализация i18next
i18next.init({
  lng: 'en',
  fallbackLng: 'en',
  resources
}, updateTeamContent);

// Переключение языков
document.querySelectorAll(".header__lang-btn").forEach(btn => {
  btn.addEventListener("click", () => {
    const lang = btn.textContent.toLowerCase();
    i18next.changeLanguage(lang, updateTeamContent);
    document.querySelectorAll(".header__lang-btn").forEach(b => b.classList.remove("header__lang-btn--active"));
    btn.classList.add("header__lang-btn--active");
  });
});